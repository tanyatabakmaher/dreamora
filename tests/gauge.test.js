import { pointOnArc, thickness, bandPath, Gauge } from "../src/components/Gauge.js";
let fail = 0;
function check(n, c, i) { if (!c) { fail++; console.log("FAIL", n, i ?? ""); } else console.log("ok  ", n, i ?? ""); }
const near = (a, b) => Math.abs(a - b) < 1e-6;
const count = (s, t) => s.split(t).length - 1;
let p = pointOnArc(0, 80);   check("0% at right end", near(p[0], 180) && near(p[1], 100), p);
p = pointOnArc(50, 80);      check("50% at top", near(p[0], 100) && near(p[1], 20), p);
p = pointOnArc(100, 80);     check("100% at left end", near(p[0], 20) && near(p[1], 100), p);
check("band gets steadily thicker", thickness(0) < thickness(25) && thickness(25) < thickness(50) && thickness(50) < thickness(100), [thickness(0), thickness(50), thickness(100)].join());
check("thin at start, clearly thicker at end", thickness(100) > 2 * thickness(0));
check("band path is a closed outline", /^M.* Z$/.test(bandPath(0, 40)));
const g0 = Gauge({ pct: 0, accumulated: 0, target: 1000, id: "a" });
check("track always drawn", g0.includes('class="g-track"'));
check("no progress at 0%", !g0.includes('class="g-fill"'));
check("three hairline separators between four parts", count(g0, 'class="g-sep"') === 3);
const g40 = Gauge({ pct: 40, accumulated: 400, target: 1000, id: "a" });
check("progress band + two round caps at 40%", count(g40, 'class="g-fill"') === 3);
check("aria label has amounts", /aria-label="התקדמות 40 אחוז, 400 ₪ מתוך 1,000 ₪"/.test(g40));
check("percent shown as text", g40.includes(">40%<"));
check("no knob, ticks or badge", !/g-knob|g-tick|g-badge/.test(g40));
check("bare gauge has no text", !Gauge({ pct: 0, bare: true, id: "b" }).includes("g-pct"));
console.log(fail === 0 ? "ALL PASSED" : fail + " FAILED"); process.exit(fail ? 1 : 0);
